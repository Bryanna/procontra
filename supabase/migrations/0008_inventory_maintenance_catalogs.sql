create or replace function api.fn_crear_mantenimiento_inventario(p_actor_uuid uuid,p_tipo text,p_codigo text,p_nombre text,p_descripcion text default null)
returns uuid language plpgsql security definer set search_path=api,public as $$
declare v_empresa integer; v_sucursal integer; v_app integer; v_email varchar(180); v_rnc varchar(20); v_tabla text; v_uuid uuid;
begin
 select f_idempresa,f_idsucursal,f_app,f_email_principal,f_rnc_principal into v_empresa,v_sucursal,v_app,v_email,v_rnc from api.t_perfiles where f_uuid=p_actor_uuid and f_activo and f_rol in ('administrator','inventory');
 if not found then raise exception 'Permiso de inventario requerido'; end if;
 v_tabla := case p_tipo when 'category' then 't_categorias_productos' when 'manufacturer' then 't_fabricantes_productos' when 'activeIngredient' then 't_principios_activos' when 'unit' then 't_unidades_medida' when 'dosageForm' then 't_formas_farmaceuticas' when 'route' then 't_vias_administracion' end;
 if v_tabla is null then raise exception 'Tipo de mantenimiento inválido'; end if;
 if length(trim(coalesce(p_nombre,'')))<2 or length(trim(p_nombre))>200 then raise exception 'Nombre de mantenimiento inválido'; end if;
 execute format('insert into api.%I(f_codigo,f_nombre,f_descripcion,f_email_principal,f_rnc_principal,f_idempresa,f_idsucursal,f_app) values($1,upper(trim($2)),nullif(trim(coalesce($3,'''')),''''),$4,$5,$6,$7,$8) returning f_uuid',v_tabla)
 into v_uuid using api.fn_normalizar_codigo_mantenimiento(coalesce(nullif(trim(p_codigo),''),p_nombre)),p_nombre,p_descripcion,v_email,v_rnc,v_empresa,v_sucursal,v_app;
 insert into api.t_eventos_auditoria(f_uuid_actor,f_tipo_evento,f_tipo_entidad,f_uuid_entidad,f_uuid_correlacion,f_metadatos_seguros,f_email_principal,f_rnc_principal,f_idempresa,f_idsucursal,f_app)
 values(p_actor_uuid,'inventory.maintenance_created',p_tipo,v_uuid,gen_random_uuid(),jsonb_build_object('type',p_tipo),v_email,v_rnc,v_empresa,v_sucursal,v_app);
 return v_uuid;
exception when unique_violation then raise exception 'Código de mantenimiento ya existe';
end $$;

create or replace function api.fn_crear_producto_inventario_relacional(
 p_actor_uuid uuid,p_codigo text,p_nombre text,p_presentacion text,p_codigo_barras text,p_uuid_categoria uuid,p_uuid_fabricante uuid,p_uuid_principio_activo uuid,p_uuid_unidad_medida uuid,p_uuid_forma_farmaceutica uuid,p_uuid_via_administracion uuid,p_registro_sanitario text,p_requiere_receta boolean,p_posiciones jsonb
) returns uuid language plpgsql security definer set search_path=api,public as $$
declare v_empresa integer; v_sucursal integer; v_app integer; v_categoria text; v_fabricante text; v_principio text; v_unidad text; v_producto uuid; v_dummy text;
begin
 select f_idempresa,f_idsucursal,f_app into v_empresa,v_sucursal,v_app from api.t_perfiles where f_uuid=p_actor_uuid and f_activo and f_rol in ('administrator','inventory');
 if not found then raise exception 'Permiso de inventario requerido'; end if;
 select f_nombre into v_categoria from api.t_categorias_productos where f_uuid=p_uuid_categoria and f_idempresa=v_empresa and f_idsucursal=v_sucursal and f_app=v_app and f_activo; if not found then raise exception 'Categoría inválida'; end if;
 select f_nombre into v_fabricante from api.t_fabricantes_productos where f_uuid=p_uuid_fabricante and f_idempresa=v_empresa and f_idsucursal=v_sucursal and f_app=v_app and f_activo; if not found then raise exception 'Fabricante inválido'; end if;
 select f_nombre into v_principio from api.t_principios_activos where f_uuid=p_uuid_principio_activo and f_idempresa=v_empresa and f_idsucursal=v_sucursal and f_app=v_app and f_activo; if not found then raise exception 'Principio activo inválido'; end if;
 select f_nombre into v_unidad from api.t_unidades_medida where f_uuid=p_uuid_unidad_medida and f_idempresa=v_empresa and f_idsucursal=v_sucursal and f_app=v_app and f_activo; if not found then raise exception 'Unidad de medida inválida'; end if;
 select f_nombre into v_dummy from api.t_formas_farmaceuticas where f_uuid=p_uuid_forma_farmaceutica and f_idempresa=v_empresa and f_idsucursal=v_sucursal and f_app=v_app and f_activo; if not found then raise exception 'Forma farmacéutica inválida'; end if;
 select f_nombre into v_dummy from api.t_vias_administracion where f_uuid=p_uuid_via_administracion and f_idempresa=v_empresa and f_idsucursal=v_sucursal and f_app=v_app and f_activo; if not found then raise exception 'Vía de administración inválida'; end if;
 v_producto := api.fn_crear_producto_inventario_detallado(p_actor_uuid,p_codigo,p_nombre,p_presentacion,p_codigo_barras,v_principio,v_fabricante,v_categoria,v_unidad,p_registro_sanitario,p_requiere_receta,p_posiciones);
 update api.t_productos set f_uuid_categoria=p_uuid_categoria,f_uuid_fabricante=p_uuid_fabricante,f_uuid_principio_activo=p_uuid_principio_activo,f_uuid_unidad_medida=p_uuid_unidad_medida,f_uuid_forma_farmaceutica=p_uuid_forma_farmaceutica,f_uuid_via_administracion=p_uuid_via_administracion where f_uuid=v_producto;
 return v_producto;
end $$;

