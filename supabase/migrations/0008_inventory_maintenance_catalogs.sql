create or replace function api.fn_normalizar_codigo_mantenimiento(p_valor text)
returns text language sql immutable as $$
  select upper(regexp_replace(trim(coalesce(p_valor,'')),'[^A-Za-z0-9ÁÉÍÓÚÜÑáéíóúüñ]+','_','g'))
$$;

